assert.throws(()=>decodeImage(new Uint8Array([1,2,3,4])),/could not be decoded/);
console.log('PASS: RGB signal fixtures, invalid JPEG rejection, and paired-image dimension checks.');
const {decodeBands,spectralAnalysis}=await import('../lib/spectral-engine.ts');
const makeNpy=(red,green,nir,scl=4,baseline=5.12)=>{
 const n=16*16;const header="{'descr': '<u2', 'fortran_order': False, 'shape': (5, 16, 16), }";const padding=16-(10+header.length+1)%16;const h=header+' '.repeat(padding)+'\n';const bytes=new Uint8Array(10+h.length+n*10);bytes.set([147,78,85,77,80,89,1,0]);new DataView(bytes.buffer).setUint16(8,h.length,true);bytes.set(new TextEncoder().encode(h),10);const v=new DataView(bytes.buffer);for(let b=0;b<5;b++)for(let i=0;i<n;i++)v.setUint16(10+h.length+(b*n+i)*2,[red,green,nir,scl,255][b],true);return decodeBands(bytes,baseline);
};
