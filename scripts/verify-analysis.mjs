import {analyze,decodeImage} from '../lib/analysis-engine.ts';
const solid=(r,g,b,w=32,h=32)=>{const data=new Uint8Array(w*h*4);for(let i=0;i<w*h;i++)data.set([r,g,b,255],i*4);return {width:w,height:h,data};};
const crop=analyze('agriculture',solid(30,150,40));
assert.equal(crop.metrics[0].value,100,'Green image should be entirely positive vegetation signal');
const water=analyze('water',solid(20,40,130));
assert.equal(water.metrics[0].value,100,'Dark blue image should meet water proxy');
const land=analyze('water',solid(210,180,130));
assert.equal(land.metrics[0].value,0,'Bright brown image must not be water');
const stable=analyze('forest',solid(30,150,40),solid(30,150,40));
assert.equal(stable.metrics[2].value,0,'Identical observations have zero coverage change');
const loss=analyze('forest',solid(160,80,50),solid(30,150,40));
assert.equal(loss.metrics[2].value,-100,'A complete green-to-brown change must lose all vegetation coverage');
